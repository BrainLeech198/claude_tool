"""插件宿主。

## 它是什么

`claude_tool/plugins/` 下每个子目录 = 一个插件。宿主负责四件事：

1. **发现** —— 扫目录、读 `plugin.json`（`manifest.py`）
2. **门禁** —— `api_version` 要对得上、`min_host` 不能比宿主新
3. **信任** —— 首次见到一律未启用；用户点过「启用」才 import（`registry.py`）
4. **喂一个 `host` 对象** —— 插件能碰到的全部就是那个对象（`host.py`）

## 它不是什么

**不是沙箱。** 插件在宿主进程里跑，`import` 那一刻就有任意代码执行权，没有隔
离可言。所以「信任确认」是唯一那道门：**不能省，也不能在 import 之后才问**。
设计说明-0.4.md 第五节 5.3 讲的就是这件事。

## 怎么加一个插件

    claude_tool/plugins/我的插件/
        plugin.json      ← 只写「是什么」：id / 名称 / 版本 / 接口版本 / 入口
        __init__.py      ← 只写「怎么算」：一个 register(host) 函数

放进去、重启启动器、在插件管理里点「启用」，就成了。
"""
